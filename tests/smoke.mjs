import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const sandbox = { window: {}, URL, AbortController, setTimeout, clearTimeout, console };
vm.createContext(sandbox);
for (const file of ['taxonomy.js', 'data.js', 'app-core.js']) vm.runInContext(read(file), sandbox, { filename: file });
const core = sandbox.window.BIOSECURITY_CORE;
const records = Array.from(sandbox.window.REPOSITORY_DATA).map(core.normalizeRecord);
assert.equal(records.length, 8, 'preserve the eight original records');
assert.equal(records.every((r) => r.sources.length && r.safeguards.length), true, 'all legacy records are source-linked');
assert.equal(records.every((r) => r.safeguards.every((s) => r.sources.some((source) => source.id === s.sourceId))), true);
assert.equal(core.filterRecords(records, { recordType: 'Guidance' }).length, 2);
assert.equal(core.filterRecords(records, { year: '2024' }).length, 5);
assert.equal(core.filterRecords(records, { safeguard: 'Red teaming' }).length, 1);
assert.equal(core.filterRecords(records, { query: 'WHO' }).length, 1);
assert.equal(core.layerStats(records, 'evaluation').count > 0, true);
assert.equal(core.layerStats([], 'evaluation').count, 0);
assert.equal(core.safeSourceUrl('javascript:alert(1)'), '');
assert.equal(core.safeSourceUrl('http://example.org'), '');
assert.equal(core.safeSourceUrl('https://example.org/test').startsWith('https://'), true);
assert.equal(core.escapeHtml('<img src=x onerror="evil()">').includes('<'), false);
assert.equal(core.normalizeRecord({ id: 'x', name: 'Test', sourceUrl: 'javascript:alert(1)', actions: ['Monitoring'] }).safeguards.length, 0);

vm.runInContext(read('database.js'), sandbox, { filename: 'database.js' });
const db = sandbox.window.BIOSECURITY_DATABASE;
let result = await db.loadPublishedRecords();
assert.equal(result.mode, 'snapshot', 'unconfigured public DB uses labeled snapshot');
sandbox.window.BIOSECURITY_CONFIG = { supabaseUrl: 'https://foo.supabase.co', supabasePublishableKey: 'public-key' };
sandbox.fetch = async (url, options) => {
  assert.equal(url, 'https://foo.supabase.co/rest/v1/published_records?select=*&order=name.asc&limit=1000');
  assert.equal(options.headers.apikey, 'public-key');
  assert.equal(options.headers.Authorization, undefined, 'do not spoof Bearer JWT');
  return { ok: true, json: async () => [{ ...sandbox.window.REPOSITORY_DATA[0] }] };
};
result = await db.loadPublishedRecords();
assert.equal(result.mode, 'database');
assert.equal(result.records.length, 1);
sandbox.fetch = async () => { throw new Error('network unavailable'); };
result = await db.loadPublishedRecords();
assert.equal(result.mode, 'snapshot', 'failed DB request is explicitly labeled');
sandbox.window.BIOSECURITY_CONFIG.supabaseUrl = 'https://example.com';
result = await db.loadPublishedRecords();
assert.equal(result.mode, 'snapshot', 'reject non-Supabase host');

const html = read('index.html');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((match) => match[1]);
assert.equal(ids.length, new Set(ids).size, 'no duplicate HTML ids');
for (const file of [...html.matchAll(/<script src="([^"]+)"/g)].map((match) => match[1])) assert.ok(fs.existsSync(path.join(root, file)), 'script exists: ' + file);
for (const id of ['recordGrid','layerStack','layerDetails','periodFilter','detailDialog','dataSourceStatus']) assert.ok(ids.includes(id));
for (const file of ['taxonomy.js','data.js','app-core.js','database.js','app.js','config.js']) new vm.Script(read(file), { filename: file });
const sql = read('supabase/001_evidence_observatory.sql');
for (const pattern of ['security_invoker = true','enable row level security','to anon, authenticated','record_changes','published_records']) assert.ok(sql.includes(pattern));
assert.ok(!/supabase(Service|Secret|DatabasePassword)\s*:/.test(read('config.js')));
console.log('PASS: data migration compatibility, filtering, safe URLs, DB fallback/read, static assets and schema guards');
